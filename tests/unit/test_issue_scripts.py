"""Unit tests for the GitHub issue tooling in scripts/ (no network calls)."""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))

import create_github_issues as cgi  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def issues():
    return cgi.parse_issues(str(ROOT / "ISSUES.md"))


def test_issue_ids_are_unique_and_sequential():
    ids = [i["id"] for i in issues()]
    assert ids == [f"I-{n:02d}" for n in range(1, len(ids) + 1)]


def test_every_issue_has_required_labels():
    for i in issues():
        labels = i["labels"]
        assert sum(lab.startswith("Order ") for lab in labels) == 1, i["id"]
        assert sum(lab.startswith("status:") for lab in labels) == 1, i["id"]
        assert any(lab in ("P0", "P1", "P2") for lab in labels), i["id"]
        assert any(lab in ("Waleed", "Aditya") for lab in labels), i["id"]


def test_every_issue_has_an_agent_prompt_and_a_milestone():
    for i in issues():
        assert "**Agent prompt**" in i["body"], i["id"]
        assert i["id"] in cgi.PART_OF, i["id"]


def test_parse_issues_strips_the_labels_line_from_the_body():
    for i in issues():
        assert "**Labels:**" not in i["body"]


def test_link_ids_rewrites_known_ids_outside_code_blocks_only():
    body = "Depends on I-01 and I-99.\n```text\nRead this issue (I-01)\n```\nAlso I-01."
    out = cgi.link_ids(body, {"I-01": 23})
    assert out.startswith("Depends on #23 and I-99.")
    assert "Read this issue (I-01)" in out
    assert out.endswith("Also #23.")


def test_footer_pattern_matches_auto_added_footer():
    footer = "text\n\n---\n_Generated by [Some Tool](https://example.com/x)_"
    assert cgi.FOOTER.search(footer)
    assert cgi.FOOTER.sub("", footer) == "text"


def test_no_ai_attribution_or_dashes_in_tracked_docs():
    banned = re.compile(r"claude|anthropic|co-authored-by|—|–", re.I)
    for name in ("AGENTS.md", "HANDOFF.md", "ISSUES.md", "README.md"):
        text = (ROOT / name).read_text(encoding="utf-8")
        assert not banned.search(text), f"{name}: {banned.search(text).group(0)!r}"
