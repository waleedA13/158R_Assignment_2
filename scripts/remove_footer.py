#!/usr/bin/env python3
"""Strip the auto-added footer from all issues and milestones. Run on your own machine:
python3 scripts/remove_footer.py
"""

import json
import re
import subprocess

R = "repos/waleedA13/158R_Assignment_2"
PAT = re.compile(r"\s*(---\s*)?_Generated by \[[^\]]+\]\([^)]+\)_\s*$")


def api(*args, payload=None):
    r = subprocess.run(
        ["gh", "api", *args] + (["--input", "-"] if payload else []),
        input=json.dumps(payload) if payload else None,
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(r.stdout) if r.stdout.strip() else None


for i in api(f"{R}/issues?state=all&per_page=100"):
    body = i.get("body") or ""
    while PAT.search(body):
        body = PAT.sub("", body)
    body = re.sub(
        r"Add `AGENTS\.md` and `[A-Z]+\.md` as two-line pointers",
        "Add `AGENTS.md` as a two-line pointer",
        body,
    )
    body = re.sub(r"`AGENTS\.md`/`[A-Z]+\.md` point to", "`AGENTS.md` points to", body)
    if body != (i.get("body") or ""):
        api("-X", "PATCH", f"{R}/issues/{i['number']}", payload={"body": body})
        print(f"cleaned issue #{i['number']}")
for m in api(f"{R}/milestones?state=all&per_page=100"):
    d = m.get("description") or ""
    while PAT.search(d):
        d = PAT.sub("", d)
    if d != (m.get("description") or ""):
        api("-X", "PATCH", f"{R}/milestones/{m['number']}", payload={"description": d})
        print(f"cleaned milestone: {m['title']}")
left = [
    i["number"]
    for i in api(f"{R}/issues?state=all&per_page=100")
    if "_Generated by [" in (i.get("body") or "")
]
print("Done. Still has footer:", left or "none")
