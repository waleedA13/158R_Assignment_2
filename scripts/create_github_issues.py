#!/usr/bin/env python3
"""Rebuild the GitHub issues from ISSUES.md, using your own gh login.

Run from the repo root on your own machine:
    python3 scripts/create_github_issues.py --dry-run     # preview, changes nothing
    python3 scripts/create_github_issues.py               # do it (asks before deleting)
    python3 scripts/create_github_issues.py --invite      # also invite Aditya as a collaborator

What it does:
 1. Makes sure every label and milestone exists; strips any auto-added footer from milestones.
 2. Deletes existing issues whose title starts with "[I-" (asks you to type "delete" first).
 3. Creates the 22 issues in order, with labels, milestone, assignees and the agent prompt.
 4. Checks no issue body contains a "Generated by" footer, then writes docs/github_issue_map.md.
"""
import argparse, json, re, subprocess, sys

REPO = "waleedA13/158R_Assignment_2"
R = f"repos/{REPO}"
PEOPLE = {"Waleed": "waleedA13", "Aditya": "AdityaJadhav17"}

PARTS = [  # (title, due date, description). Titles must stay the same so existing milestones are reused.
    ("Part 1: Setup and decision", "2026-11-22", "Repo scaffold, spec, checker, dataset/task decision."),
    ("Part 2: Data and task", "2026-11-24", "Shared split, task framing, EDA, preprocessing, related-work notes."),
    ("Part 3: Models and evaluation", "2026-11-25", "Baselines, course model, main model, test evaluation."),
    ("Part 4: Notebook", "2026-11-27", "Error analysis, comparison to literature, tuning if on track; assemble and export workbook. Notebook frozen Fri evening."),
    ("Part 5: Presentation and submission", "2026-11-30", "Slides from Wed 11-25, rehearse Sat, record Sun, submit Mon."),
    ("Part 6: Peer grading", "2026-12-08", "Each member completes peer grading (week 11)."),
]
PART_OF = {"I-01": 0, "I-02": 0, "I-03": 0, "I-18": 0, "I-04": 1, "I-05": 1, "I-06": 1, "I-07": 1, "I-14": 1,
           "I-08": 2, "I-09": 2, "I-10": 2, "I-12": 2,
           "I-11": 3, "I-13": 3, "I-15": 3, "I-16": 3, "I-17": 3,
           "I-19": 4, "I-20": 4, "I-21": 4, "I-22": 5}

ORDER_COLORS = ["0e8a16", "2c9a2c", "4aa43f", "6aae52", "8ab865", "a9c278", "c8cc8b", "e0c77a", "e8b060", "ef9946", "f6822c"]
LABEL_STYLE = {  # name: (color, description) used only when a label has to be created
    "P0": ("b60205", "Blocks submission. Do first"),
    "P1": ("d93f0b", "Needed for a solid 4/5 on its section"),
    "P2": ("fbca04", "Stretch work toward a 5/5"),
    "Waleed": ("c5def5", "Owner: Waleed (data, setup, notebook assembly, submission)"),
    "Aditya": ("c5def5", "Owner: Aditya (modeling, evaluation, related work)"),
}
PREFIX_COLOR = {"type": "1d76db", "area": "5319e7", "status": "bfbfbf", "owner": "0e8a16"}
FOOTER = re.compile(r"\s*(---\s*)?_Generated by \[[^\]]+\]\([^)]+\)_\s*$")


def api(method, path, payload=None, dry=False, allow_fail=False):
    if dry and method != "GET":
        print(f"  [dry] {method} {path}")
        return {}
    cmd = ["gh", "api", "-X", method, path]
    r = subprocess.run(cmd + (["--input", "-"] if payload is not None else []),
                       input=json.dumps(payload) if payload is not None else None, capture_output=True, text=True)
    if r.returncode != 0:
        if allow_fail:
            return {"_error": (r.stdout + r.stderr).strip()}
        sys.exit(f"gh api failed: {method} {path}\n{r.stdout}\n{r.stderr}")
    return json.loads(r.stdout) if r.stdout.strip() else {}


def parse_issues(path="ISSUES.md"):
    text = open(path, encoding="utf-8").read()
    issues = []
    for b in re.split(r"(?m)^### ", text)[1:]:
        head, _, rest = b.partition("\n")
        m = re.match(r"(I-\d\d) · (.+)", head.strip())
        if not m:
            continue
        lab = re.search(r"\*\*Labels:\*\*(.+)", rest)
        labels = re.findall(r"`([^`]+)`", lab.group(1)) if lab else []
        body = re.sub(r"\*\*Labels:\*\*.+\n", "", rest).strip()
        issues.append({"id": m.group(1), "title": m.group(2).strip(), "labels": labels, "body": body})
    return issues


def link_ids(body, num):
    """Turn I-NN into #number outside code blocks (prompts keep I-NN so they match ISSUES.md)."""
    parts = re.split(r"(```.*?```)", body, flags=re.S)
    for i in range(0, len(parts), 2):
        parts[i] = re.sub(r"\bI-\d\d\b", lambda m: f"#{num[m.group(0)]}" if m.group(0) in num else m.group(0), parts[i])
    return "".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--yes", action="store_true", help="skip the delete confirmation")
    ap.add_argument("--invite", action="store_true", help="invite Aditya as a collaborator (push access)")
    a = ap.parse_args()
    dry = a.dry_run

    me = api("GET", "user", allow_fail=True).get("login", "unknown")
    print(f"Signed in to gh as: {me}")
    aditya_ok = "_error" not in api("GET", f"{R}/assignees/{PEOPLE['Aditya']}", allow_fail=True)
    if not aditya_ok:
        print("Note: Aditya is not a collaborator yet, so his issues will be labelled but unassigned.")
    issues = parse_issues()
    assert len(issues) == 22, f"expected 22 issues in ISSUES.md, found {len(issues)}"

    if a.invite:
        print("== Inviting Aditya")
        r = api("PUT", f"{R}/collaborators/{PEOPLE['Aditya']}", {"permission": "push"}, dry, allow_fail=True)
        print("  " + (r.get("_error") or "invitation sent (he must accept it before he can be assigned)"))

    print("== Labels")
    have = {l["name"] for l in api("GET", f"{R}/labels?per_page=100")}
    needed = sorted({l for i in issues for l in i["labels"]})
    for l in needed:
        if l in have:
            continue
        if l.startswith("Order "):
            k = int(l.split()[1])
            color, desc = ORDER_COLORS[min(k, 11) - 1], f"Step {k} of 11. Start when its dependencies are closed. Same order = can run in parallel"
        else:
            color, desc = LABEL_STYLE.get(l, (PREFIX_COLOR.get(l.split(":")[0], "ededed"), ""))
        print(f"  create label {l}")
        api("POST", f"{R}/labels", {"name": l, "color": color, "description": desc}, dry)

    print("== Milestones")
    ms = {m["title"]: m for m in api("GET", f"{R}/milestones?state=all&per_page=100")}
    for title, due, desc in PARTS:
        if title not in ms:
            print(f"  create milestone {title}")
            ms[title] = api("POST", f"{R}/milestones", {"title": title, "due_on": f"{due}T23:59:00Z", "description": desc}, dry) or {"number": 0}
        elif (ms[title].get("description") or "") != desc or (ms[title].get("due_on") or "")[:10] != due:
            print(f"  update milestone: {title} (due {due})")
            api("PATCH", f"{R}/milestones/{ms[title]['number']}", {"description": desc, "due_on": f"{due}T23:59:00Z"}, dry)

    old = [i for i in api("GET", f"{R}/issues?state=all&per_page=100")
           if "pull_request" not in i and i["title"].startswith("[I-")]
    if old:
        print(f"== Deleting {len(old)} existing [I-..] issues: " + ", ".join(f"#{i['number']}" for i in sorted(old, key=lambda x: x['number'])))
        if not dry:
            if not a.yes and input('This is permanent. Type "delete" to continue: ').strip() != "delete":
                sys.exit("Stopped. Nothing deleted, no issues created.")
            for i in old:
                r = subprocess.run(["gh", "issue", "delete", str(i["number"]), "-R", REPO, "--yes"], capture_output=True, text=True)
                if r.returncode != 0:
                    sys.exit(f"Could not delete #{i['number']}: {r.stderr.strip()}\n(Deleting issues needs admin rights on the repo.)")
                print(f"  deleted #{i['number']}")

    print("== Creating issues")
    num, unassigned = {}, []
    for n, iss in enumerate(issues, start=1):
        who = [PEOPLE[p] for p in ("Waleed", "Aditya") if p in iss["labels"] and (p != "Aditya" or aditya_ok)]
        if "Aditya" in iss["labels"] and not aditya_ok:
            unassigned.append(iss["id"])
        payload = {"title": f"[{iss['id']}] {iss['title']}", "body": link_ids(iss["body"], num),
                   "labels": iss["labels"], "milestone": ms[PARTS[PART_OF[iss["id"]]][0]].get("number"), "assignees": who}
        r = api("POST", f"{R}/issues", payload, dry, allow_fail=True)
        if "_error" in r and who:
            payload["assignees"] = [u for u in who if u != PEOPLE["Aditya"]]
            unassigned.append(iss["id"])  # assignment refused
            r = api("POST", f"{R}/issues", payload, dry, allow_fail=True)
        if "_error" in r:
            sys.exit(f"Failed creating {iss['id']}: {r['_error']}")
        num[iss["id"]] = r.get("number", n)
        print(f"  {iss['id']} -> #{num[iss['id']]}  [{', '.join(payload['assignees']) or 'unassigned'}]")

    if dry:
        print("Dry run only. Nothing was changed.")
        return

    print("== Checking")
    bad = [i["number"] for i in api("GET", f"{R}/issues?state=open&per_page=100") if "_Generated by [" in (i.get("body") or "")]
    print("  footer found on: " + (", ".join(f"#{b}" for b in bad) if bad else "none"))
    with open("docs/github_issue_map.md", "w", encoding="utf-8") as f:
        f.write("# GitHub issue map\n\n| ID | GitHub |\n|---|---|\n")
        for iid, n in num.items():
            f.write(f"| {iid} | #{n} |\n")
    print("  wrote docs/github_issue_map.md")
    if unassigned:
        print(f"  Aditya could not be assigned on {len(unassigned)} issues (not a collaborator yet).")
        print("  After he accepts the invite, run:  python3 scripts/assign_aditya.py")
    print("Done.")


if __name__ == "__main__":
    main()
